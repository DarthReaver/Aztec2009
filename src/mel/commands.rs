pub fn resolve_targets(s: &Session, names: &[String]) -> Result<Vec<NodeId>, String> {
    if names.is_empty() {
        if s.scene.selection.is_empty() {
            return Err("Nothing is selected".to_string());
        }
        return Ok(s.scene.selection.clone());
    }
    names
        .iter()
        .map(|n| s.scene.find(n).ok_or_else(|| format!("No object matches name: {}", n)))
        .collect()
}

